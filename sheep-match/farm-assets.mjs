const animalClips = new Map();
for (const [species,clips] of Object.entries(animalAnimationMetadata)) {
  for (const [key,clip] of Object.entries(clips)) {
    animalClips.set(`${species}.${key}`,Object.freeze({
          urls:Object.freeze(clip.paths.map(path=>new URL(`./assets/farm/${path}`,import.meta.url).href)),
          fps:clip.fps,
          loop:clip.loop,
          durationMs:clip.durationMs,
          mirrorX:clip.mirrorX
        }));
  }
}
export function farmAnimalClip(species,state='idle',direction='front') {
  species=String(species).toLowerCase();
  return animalClips.get(`${species}.${direction}.${state}`) ||animalClips.get(`${species}.front.idle`) ||animalClips.get('chicken.front.idle');
}
export function farmAnimalUrl(species,state='idle',direction='front',frame=0) {
  const clip=farmAnimalClip(species,state,direction);
  return clip.urls[Math.max(0,Math.floor(frame))%clip.urls.length];
}
