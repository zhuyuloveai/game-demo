#!/usr/bin/env python3
"""Deterministic transparent runtime derivatives; originals remain untouched. Requires Pillow."""
from pathlib import Path
import hashlib,json,subprocess
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'docs/art-packs/sumikko-farm-v1/assets'
TARGET=ROOT/'assets/farm-runtime'
STATES=ROOT/'docs/art-packs/sumikko-farm-v1/plant-states'
state_manifest=json.loads((STATES/'manifest.json').read_text())
ANIMALS=ROOT/'docs/art-packs/sumikko-farm-v1/animal-states'
animal_manifest=json.loads((ANIMALS/'manifest.json').read_text())
inputs=[(source,source.relative_to(SOURCE).as_posix()[:-4],1) for source in sorted(SOURCE.rglob('*.png'))]
inputs += [(STATES/entry['path'],'plant-states/'+entry['group']+'/'+entry['key'],entry['displayScale']) for entry in state_manifest['assets'] if entry['status']!='existing']
inputs += [(ANIMALS/entry['path'],'animal-states/'+entry['key'],entry['displayScale']) for entry in animal_manifest['assets'] if entry['status']!='existing']
metadata={}
for source,key,display_scale in inputs:
    im=Image.open(source).convert('RGBA'); original=list(im.size)
    im.thumbnail((512,512),Image.Resampling.LANCZOS)
    target=TARGET/(key+'.png');target.parent.mkdir(parents=True,exist_ok=True)
    im.save(target,optimize=True)
    alpha=im.getchannel('A'); bounds=alpha.point(lambda a:255 if a>=16 else 0).getbbox()
    # Sample cropped visual alpha, excluding clear margins and transparent holes.
    mask=alpha.crop(bounds).resize((64,64),Image.Resampling.BOX)
    rows=[]
    for y in range(64):
        row=sum((1<<x) for x in range(64) if mask.getpixel((x,y))>=24)
        rows.append(format(row,'016x'))
    metadata[key]={'path':'assets/farm-runtime/'+key+'.png','width':im.width,'height':im.height,'bounds':list(bounds),'anchor':[.5,1],'scale':display_scale,'mask':{'size':64,'rows':rows},'source':source.relative_to(ROOT).as_posix(),'sourceSha256':hashlib.sha256(source.read_bytes()).hexdigest(),'originalSize':original}
(ROOT/'farm-runtime-art-metadata.mjs').write_text('// Generated by tools/build-runtime-art.py; metadata is presentation-only, never saved.\nexport const RUNTIME_ART_METADATA = '+json.dumps(metadata,ensure_ascii=False,separators=(',',':'))+';\n')
(TARGET/'manifest.json').write_text(json.dumps({'sourceCommit':subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip(),'sourcePack':'docs/art-packs/sumikko-farm-v1','plantStateManifest':'docs/art-packs/sumikko-farm-v1/plant-states/manifest.json','animalStateManifest':'docs/art-packs/sumikko-farm-v1/animal-states/manifest.json','maxEdge':512,'assets':[{'key':key,'path':data['path'],'source':data['source'],'sourceSha256':data['sourceSha256'],'bytes':(ROOT/data['path']).stat().st_size,'width':data['width'],'height':data['height']} for key,data in metadata.items()]},ensure_ascii=False,indent=2)+'\n')
print(f'{len(metadata)} PNGs, {sum(p.stat().st_size for p in TARGET.rglob("*.png")):,} bytes')
