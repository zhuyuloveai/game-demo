#!/usr/bin/env python3
"""Reproducible full-canvas derivatives of the approved layered shelter pack.

Requires Pillow. Does not crop, redraw, mutate source assets, or rescale any
source-space layout coordinates. Alpha masks use the same full canvas as art.
"""
from pathlib import Path
import hashlib
import json
from PIL import Image
ROOT = Path(__file__).resolve().parents[1]
PACK = ROOT / 'docs/art-packs/sumikko-farm-v1/shelter-layers-v2'
OUT = ROOT / 'assets/farm-runtime/shelters-v2'
KINDS = ['chicken', 'cow', 'pig', 'sheep', 'lamb']
LAYERS = {'ground':'01-ground', 'buildingShadow':'02-building-shadow', 'rearFence':'03-rear-fence', 'building':'04-building', 'frontFence':'07-front-fence'}
STATES = ['hungry', 'producing', 'ready']
assets = {}
specs = {}

def generate(source, key, max_edge, anchor):
    original = Image.open(source).convert('RGBA')
    image = original.copy()
    image.thumbnail((max_edge, max_edge), Image.Resampling.LANCZOS)
    target = OUT / (key + '.png')
    target.parent.mkdir(parents=True, exist_ok=True)
    existing = Image.open(target).convert('RGBA') if target.exists() else None
    if existing is None or existing.size != image.size or existing.tobytes() != image.tobytes():
        image.save(target, optimize=True)
    alpha = image.getchannel('A')
    size = 128 if key.startswith('layers/') else 64
    sampled = alpha.resize((size, size), Image.Resampling.BOX)
    rows = [format(sum(1 << x for x in range(size) if sampled.getpixel((x, y)) >= 24), f'0{size // 4}x') for y in range(size)]
    data = {'key':key, 'path':target.relative_to(ROOT).as_posix(), 'width':image.width, 'height':image.height,
            'bounds':[0, 0, image.width, image.height], 'paintedBounds':list(alpha.point(lambda a:255 if a >= 16 else 0).getbbox()),
            'anchor':anchor, 'scale':1, 'mask':{'size':size, 'rows':rows},
            'source':source.relative_to(ROOT).as_posix(), 'sourceSha256':hashlib.sha256(source.read_bytes()).hexdigest(),
            'originalSize':list(original.size)}
    assets[key] = data
    return key

for kind in KINDS:
    source_dir = PACK / kind
    layout = json.loads((source_dir / 'layout.json').read_text())
    canvas, animal = layout['canvas'], layout['animalCanvas']
    layer_keys = {name:generate(source_dir/'layers'/(file+'.png'), f'layers/{kind}/{name}', 600,
                        [canvas['commonAnchor'][0]/canvas['width'], canvas['commonAnchor'][1]/canvas['height']]) for name,file in LAYERS.items()}
    animal_keys = {}
    for state in STATES:
        anchor = [animal['anchor'][0]/animal['width'], animal['anchor'][1]/animal['height']]
        animal_keys[state] = {
            'body':generate(source_dir/'animals'/f'{kind}-{state}.png', f'animals/{kind}/{state}', 360, anchor),
            'shadow':generate(source_dir/'animals'/f'{kind}-{state}-shadow.png', f'animals/{kind}/{state}-shadow', 360, anchor)}
    fields = ['canvas','footprint','buildingSupport','standingRegion','standingExclusions','entry','occlusion','animalCanvas','referenceAnimalPlacements','animals']
    specs[kind] = {field:layout[field] for field in fields}
    specs[kind].update({'id':kind, 'layerKeys':layer_keys, 'animalKeys':animal_keys,
                       'referenceSlots':layout['referenceAnimalPlacements'],
                       'source':(source_dir/'layout.json').relative_to(ROOT).as_posix(),
                       'sourceSha256':hashlib.sha256((source_dir/'layout.json').read_bytes()).hexdigest()})

(ROOT / 'farm-runtime-shelters-metadata.mjs').write_text(
    '// Generated by tools/build-runtime-shelters.py. Full-canvas art; source-space coordinates remain unchanged.\n'
    'export const SHELTER_ASSET_METADATA = ' + json.dumps(assets, ensure_ascii=False, separators=(',',':')) + ';\n'
    'export const SHELTER_SPATIAL_METADATA = ' + json.dumps(specs, ensure_ascii=False, separators=(',',':')) + ';\n')
manifest = {'version':2, 'sourcePack':PACK.relative_to(ROOT).as_posix(), 'facilities':KINDS,
            'maxLayerEdge':600, 'maxAnimalEdge':360, 'assets':[{'key':key,'path':data['path'],'source':data['source'],
              'sourceSha256':data['sourceSha256'],'width':data['width'],'height':data['height'],
              'bytes':(ROOT/data['path']).stat().st_size} for key,data in assets.items()]}
(OUT/'manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2)+'\n')
print(f'{len(assets)} PNGs, {sum((ROOT/d["path"]).stat().st_size for d in assets.values()):,} bytes')
