#!/usr/bin/env python3
"""Bundle the reviewed seasonal layouts; no image pixels are modified."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
keys = ['spring', 'summer', 'autumn', 'winter']
colors = ['#e6edcf', '#d6ead3', '#f4dfbf', '#e4e6f3']
shorts = ['春', '夏', '秋', '冬']
designs = []
for key, color, short in zip(keys, colors, shorts):
    design = json.loads((root / 'docs' / 'farm-designs' / f'{key}.json').read_text())
    assert design['key'] == key and len(design['groups']) == len(design['rewards']) == 6
    design.update(color=color, short=short)
    for field in ['background', 'stickers']:
        assert (root / 'assets' / 'farm' / design[field]).is_file()
    designs.append(design)
(root / 'farm-designs.mjs').write_text('// Generated by tools/sync-farm-designs.py from reviewed seasonal layouts.\nexport const FARM_DESIGNS = ' + json.dumps(designs, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('Bundled four distinct seasonal farm designs.')
