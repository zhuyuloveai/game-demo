#!/usr/bin/env python3
"""Copy approved SVG components exactly and record anchored runtime metadata."""
from pathlib import Path
import json,hashlib,shutil
ROOT=Path(__file__).resolve().parents[1]
PACK=ROOT/'docs/art-packs/sumikko-farm-v1'
metadata={}
for group in ['environment','building-states']:
    for entry in json.loads((PACK/group/'manifest.json').read_text())['assets']:
        source=PACK/group/entry['path']; target=ROOT/'assets/farm-runtime'/group/(entry['id']+'.svg')
        target.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(source,target)
        metadata[group+'/'+entry['id']]={**entry,'path':target.relative_to(ROOT).as_posix(),'source':source.relative_to(ROOT).as_posix(),'sha256':hashlib.sha256(source.read_bytes()).hexdigest()}
(ROOT/'farm-runtime-environment-metadata.mjs').write_text('// Generated by tools/build-runtime-environment.py; presentation only.\nexport const ENVIRONMENT_ART_METADATA = '+json.dumps(metadata,ensure_ascii=False,separators=(',',':'))+';\n')
(ROOT/'assets/farm-runtime/environment-manifest.json').write_text(json.dumps({'assets':list(metadata.values())},ensure_ascii=False,indent=2)+'\n')
print(f'{len(metadata)} anchored SVG components')
