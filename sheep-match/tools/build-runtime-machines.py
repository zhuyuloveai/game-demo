#!/usr/bin/env python3
"""Package approved independent parts only; diagnostic phases are never runtime frames."""
import hashlib,json,shutil
from pathlib import Path
from PIL import Image,ImageChops
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'docs/art-packs/farm-art-completion-v1/machines'
DEST=ROOT/'assets/farm-runtime/machine-parts-v1'
legacy_text=(ROOT/'farm-runtime-art-metadata.mjs').read_text()
legacy=json.loads(legacy_text[legacy_text.index('{'):legacy_text.rindex('}')+1])
metadata={};assets=[]
for id in ('feed-mill','windmill','loom','juice-press','sewing-machine'):
    source=SOURCE/id;spec=json.loads((source/'manifest.json').read_text());reg=spec['legacyRegistration']
    key=('decor/' if id=='windmill' else 'buildings/')+id;old=legacy[key]
    files={'base':'layers/01-base.png'}
    if len(spec['layers'])==3:files['foreground']='layers/03-foreground.png'
    files['moving']='sources/rotor-plane.png' if spec['animation']['type']=='rotor' else 'layers/02-moving.png'
    paths={}
    for name,relative in files.items():
        target=DEST/id/(name+'.png');target.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(source/relative,target)
        path=target.relative_to(ROOT).as_posix();paths[name]=path
        assets.append({'path':path,'source':(source/relative).relative_to(ROOT).as_posix(),'sha256':hashlib.sha256(target.read_bytes()).hexdigest()})
    # Union alpha covers the moving part's sweep without expanding the logical footprint.
    alpha=Image.new('L',(800,750))
    for phase in source.glob('previews/phase-*.png'):alpha=ImageChops.lighter(alpha,Image.open(phase).getchannel('A'))
    alpha=alpha.resize((64,64),Image.Resampling.BOX)
    mask={'size':64,'rows':[f'{sum(1<<x for x in range(64) if alpha.getpixel((x,y))>=16):016x}' for y in range(64)]}
    def point(p):
        b=old['bounds'];size=spec['sourceCanvas'];canvas=reg['canvas']
        return [(72+(b[0]+p[0]*(b[2]-b[0]))*size[0]/canvas[0]/2)/800,(75+(b[1]+p[1]*(b[3]-b[1]))*size[1]/canvas[1]/2)/750]
    meta={'id':id,'key':'machine-parts/'+id,'width':800,'height':750,'bounds':[0,0,800,750],
          'anchor':[spec['anchor'][0]/800,spec['anchor'][1]/750],'visualWidth':reg['fullCanvasDisplayWidth'],
          'groundPoint':old['groundPoint'],'scale':1,'allowedRotations':old['allowedRotations'],
          'mask':mask,'layers':paths,'pivot':spec['pivot'],'motion':spec['animation'],
          'legacyKey':key,'legacyRegistration':reg}
    if id in ('feed-mill','windmill'):meta['rotorRadius']={'feed-mill':87,'windmill':222.5}[id]
    for field in ('entry','outputAnchor'):
        if field in old:meta[field]=point(old[field])
    if 'support' in old:meta['support']=[point(p) for p in old['support']]
    metadata[id]=meta
(DEST/'manifest.json').write_text(json.dumps({'version':1,'sets':list(metadata),'assets':assets},indent=2)+'\n')
(ROOT/'farm-runtime-machines-metadata.mjs').write_text('// Generated by tools/build-runtime-machines.py. Approved layers, no diagnostic frames.\nexport const MACHINE_PART_METADATA = '+json.dumps(metadata,separators=(',',':'))+';\n')
print(f'Packaged {len(metadata)} mechanisms / {len(assets)} independent PNG resources')
